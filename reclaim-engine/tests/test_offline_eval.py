"""Phase 27 tests — offline policy evaluation (architecture §7, §9.2).

Two kinds of test here. The first kind checks the estimators against a known
truth, because an evaluator nobody has validated is worse than no evaluator. The
second kind checks the refusals — an importance-weighted estimator will always
return *a* number, and most of this module's value is knowing when that number
means nothing.
"""
import hashlib
from decimal import Decimal

import pytest

from reclaim.bandit import (
    Action,
    EpsilonGreedyBandit,
    EpsilonGreedyConfig,
    FixedActionPolicy,
    GreedyPolicy,
    LoggingPolicyEcho,
)
from reclaim.offline_eval import (
    LoggedDecision,
    OfflineEvalError,
    direct_method,
    doubly_robust,
    ips,
    should_deploy,
)
from reclaim.recovery import Channel

D = Decimal

A1 = Action(Channel.UPI_RETRY, 10, "m1")
A2 = Action(Channel.WHATSAPP_NUDGE, 18, "m2")
KEYS = [A1.key, A2.key]

# The ground truth the estimators are graded against.
TRUE_REWARD = {A1.key: D("0.2"), A2.key: D("0.8")}


def row(uid="u1", ctx="ctx", action=None, propensity="0.5", reward="1"):
    return LoggedDecision(unit_id=uid, context_key=ctx,
                          action_key=action or A1.key,
                          propensity=D(propensity), reward=D(reward))


def _draw(seed: str) -> int:
    return int.from_bytes(hashlib.sha256(seed.encode()).digest()[:8], "big") % 100


def make_log(n=400, epsilon="0.10", seed="r"):
    """A log generated by a real bandit against the true reward rates.

    ``seed`` varies the reward realisations, so the same policy can be replayed
    against independent draws — which is what makes a variance claim testable
    rather than an assertion about one lucky sample.
    """
    bandit = EpsilonGreedyBandit([A1, A2],
                                 config=EpsilonGreedyConfig(epsilon=D(epsilon)))
    log = []
    for i in range(n):
        choice = bandit.choose("ctx", f"u{i}")
        rate = TRUE_REWARD[choice.action.key]
        reward = D("1") if _draw(f"{seed}:{i}") < rate * 100 else D("0")
        log.append(LoggedDecision(f"u{i}", "ctx", choice.action.key,
                                  choice.propensity, reward))
    return bandit, log


def perfect_model(context_key, action_key):
    return TRUE_REWARD[action_key]


def useless_model(context_key, action_key):
    return D("0")


ALWAYS_A2 = FixedActionPolicy(A2.key).probability
ALWAYS_A1 = FixedActionPolicy(A1.key).probability


# --------------------------------------------------------------------------
# LoggedDecision — the refusals start here
# --------------------------------------------------------------------------
def test_a_log_row_validates_its_fields():
    ok = ("u1", "ctx", A1.key, D("0.5"), D("1"))
    for i in range(3):                       # each string field must be non-empty
        bad = list(ok)
        bad[i] = ""
        with pytest.raises(OfflineEvalError):
            LoggedDecision(*bad)
    with pytest.raises(OfflineEvalError):
        LoggedDecision("u1", "ctx", A1.key, 0.5, D("1"))       # propensity float
    with pytest.raises(OfflineEvalError):
        LoggedDecision("u1", "ctx", A1.key, D("0.5"), 1)       # reward int


def test_a_zero_propensity_is_refused_not_worked_around():
    """A logged action the policy could not have taken puts a zero in the
    denominator. There is no defensible way to continue."""
    with pytest.raises(OfflineEvalError) as exc:
        row(propensity="0")
    assert "zero in the denominator" in str(exc.value)
    with pytest.raises(OfflineEvalError):
        row(propensity="-0.1")


def test_a_propensity_above_one_is_refused():
    with pytest.raises(OfflineEvalError):
        row(propensity="1.5")


def test_an_empty_log_cannot_be_evaluated():
    with pytest.raises(OfflineEvalError):
        ips([], ALWAYS_A1, actions=KEYS)
    with pytest.raises(OfflineEvalError):
        ips(["not a row"], ALWAYS_A1, actions=KEYS)


# --------------------------------------------------------------------------
# The identity every IPS implementation must satisfy
# --------------------------------------------------------------------------
def test_evaluating_the_logging_policy_returns_the_logs_own_mean():
    """If this does not hold exactly, no other number the module produces can be
    trusted. It is the reason propensities sum to exactly one."""
    bandit, log = make_log()
    estimate = ips(log, LoggingPolicyEcho(bandit).probability, actions=KEYS)
    assert estimate.value == estimate.logged_mean
    assert estimate.improvement_over_logged() == D("0.0000")


def test_ips_recovers_a_known_value_when_the_log_covers_it_well():
    """With plenty of exploration both arms are well covered and IPS lands close
    to the truth."""
    _bandit, log = make_log(n=2000, epsilon="0.50")
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert abs(estimate.value - TRUE_REWARD[A2.key]) < D("0.08")
    assert estimate.is_usable


def test_a_better_policy_estimates_higher_than_a_worse_one():
    _bandit, log = make_log(n=2000, epsilon="0.50")
    good = ips(log, ALWAYS_A2, actions=KEYS)
    bad = ips(log, ALWAYS_A1, actions=KEYS)
    assert good.value > bad.value


# --------------------------------------------------------------------------
# Identification — the refusal that matters most
# --------------------------------------------------------------------------
def test_a_policy_the_log_never_covers_is_not_identified():
    """No amount of reweighting can say what an action nobody took would have
    achieved. The answer is None, not a number with a caveat."""
    log = [row(uid=f"u{i}", action=A1.key) for i in range(20)]
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert estimate.value is None
    assert estimate.identified is False
    assert estimate.unsupported == ("ctx",)
    assert "NOT IDENTIFIED" in estimate.note
    assert estimate.improvement_over_logged() is None
    assert estimate.is_usable is False


def test_dr_refuses_the_same_unidentified_case():
    log = [row(uid=f"u{i}", action=A1.key) for i in range(20)]
    estimate = doubly_robust(log, ALWAYS_A2, actions=KEYS, reward_model=perfect_model)
    assert estimate.value is None and estimate.identified is False


def test_many_uncovered_contexts_are_summarised_not_dumped():
    log = [row(uid=f"u{i}", ctx=f"c{i}", action=A1.key) for i in range(6)]
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert len(estimate.unsupported) == 6
    assert ", ..." in estimate.note            # only the first three are named


def test_a_policy_that_acts_nowhere_is_identified_but_worth_nothing():
    """Degenerate but reachable: the target assigns no probability to any action
    in the log's action set, so every weight is zero."""
    log = [row(uid=f"u{i}") for i in range(10)]
    nothing = FixedActionPolicy("some-action-not-in-the-set").probability
    estimate = ips(log, nothing, actions=KEYS)
    assert estimate.identified is True
    assert estimate.value == D("0.0000")
    assert estimate.ess == D("0") and estimate.max_weight_share == D("0")


# --------------------------------------------------------------------------
# Diagnostics — an estimate is allowed to be untrustworthy, not silently so
# --------------------------------------------------------------------------
def test_a_thinly_explored_target_is_flagged_as_concentrated():
    """A2 is only ever taken on exploration, so the estimate leans on a handful
    of heavily-weighted rows. It must say so."""
    _bandit, log = make_log(n=400, epsilon="0.02")
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert estimate.value is not None
    assert estimate.concentrated is True
    assert estimate.is_usable is False
    assert "CONCENTRATED" in estimate.note
    assert estimate.ess < D("0.10") * D(estimate.n)


def test_a_single_dominant_row_is_reported():
    log = ([row(uid="whale", action=A2.key, propensity="0.0001", reward="1")]
           + [row(uid=f"u{i}", action=A2.key, propensity="0.9", reward="1")
              for i in range(20)])
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert estimate.max_weight_share > D("0.50")
    assert estimate.concentrated is True
    assert "carries" in estimate.note


def test_a_well_covered_estimate_is_not_flagged():
    _bandit, log = make_log(n=2000, epsilon="0.50")
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert estimate.concentrated is False
    assert "CONCENTRATED" not in estimate.note


# --------------------------------------------------------------------------
# Clipping — variance down, bias in a stated direction
# --------------------------------------------------------------------------
def test_clipping_is_counted_and_its_direction_stated():
    _bandit, log = make_log(n=400, epsilon="0.02")
    clipped = ips(log, ALWAYS_A2, actions=KEYS, clip=D("5"))
    assert clipped.clipped > 0
    assert "biased *toward the logging policy*" in clipped.note
    unclipped = ips(log, ALWAYS_A2, actions=KEYS)
    # clipping pulls the estimate back toward what was actually deployed
    assert abs(clipped.value - clipped.logged_mean) < abs(unclipped.value
                                                          - unclipped.logged_mean)


def test_clip_must_be_a_positive_decimal():
    _bandit, log = make_log(n=20)
    for bad in (5, D("0"), D("-1")):
        with pytest.raises(OfflineEvalError):
            ips(log, ALWAYS_A2, actions=KEYS, clip=bad)
        with pytest.raises(OfflineEvalError):
            doubly_robust(log, ALWAYS_A2, actions=KEYS,
                          reward_model=perfect_model, clip=bad)


def test_dr_clipping_is_reported_too():
    _bandit, log = make_log(n=400, epsilon="0.02")
    estimate = doubly_robust(log, ALWAYS_A2, actions=KEYS,
                             reward_model=perfect_model, clip=D("5"))
    assert estimate.clipped > 0 and "biased toward the logging policy" in estimate.note


# --------------------------------------------------------------------------
# The direct method, and what DR buys over both
# --------------------------------------------------------------------------
def test_the_direct_method_is_exactly_as_wrong_as_its_model():
    _bandit, log = make_log(n=200)
    good = direct_method(log, ALWAYS_A2, actions=KEYS, reward_model=perfect_model)
    assert good.value == TRUE_REWARD[A2.key].quantize(D("0.0001"))
    bad = direct_method(log, ALWAYS_A2, actions=KEYS, reward_model=useless_model)
    assert bad.value == D("0.0000")
    assert "exactly as wrong as the model is" in good.note
    assert good.ess is None                    # no importance weights involved
    assert good.concentrated is False          # nothing to be concentrated in
    assert good.is_usable is True


def test_dr_with_a_useless_reward_model_reduces_to_ips():
    """The residual carries everything when the model predicts zero."""
    _bandit, log = make_log(n=400, epsilon="0.30")
    a = ips(log, ALWAYS_A2, actions=KEYS)
    b = doubly_robust(log, ALWAYS_A2, actions=KEYS, reward_model=useless_model)
    assert a.value == b.value


def test_dr_survives_corrupted_propensities_when_the_model_is_right():
    """The property that earns DR its extra moving part, and the situation a real
    deployment is actually in: nobody's propensities survive an incident intact."""
    _bandit, log = make_log(n=400, epsilon="0.30")
    corrupted = [LoggedDecision(r.unit_id, r.context_key, r.action_key,
                                D("0.5"), r.reward)          # wrong on purpose
                 for r in log]
    naive = ips(corrupted, ALWAYS_A2, actions=KEYS)
    robust = doubly_robust(corrupted, ALWAYS_A2, actions=KEYS,
                           reward_model=perfect_model)
    truth = TRUE_REWARD[A2.key]
    assert abs(robust.value - truth) < abs(naive.value - truth)
    assert abs(robust.value - truth) < D("0.10")


def test_dr_has_lower_error_than_ips_across_independent_draws():
    """DR's advantage is lower *variance*, not a smaller error on every sample —
    on any single thinly-explored log IPS can happen to land closer. So the claim
    is made where it is true: averaged over independent reward draws.
    """
    truth = TRUE_REWARD[A2.key]
    ips_error = dr_error = D("0")
    seeds = [f"seed-{i}" for i in range(12)]
    for seed in seeds:
        _bandit, log = make_log(n=400, epsilon="0.05", seed=seed)
        ips_error += abs(ips(log, ALWAYS_A2, actions=KEYS).value - truth)
        dr_error += abs(doubly_robust(log, ALWAYS_A2, actions=KEYS,
                                      reward_model=perfect_model).value - truth)
    assert dr_error / len(seeds) < ips_error / len(seeds)


