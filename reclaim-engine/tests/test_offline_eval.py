def test_an_unidentified_estimate_is_never_shipped():
    log = [row(uid=f"u{i}", action=A1.key) for i in range(20)]
    verdict = should_deploy(ips(log, ALWAYS_A2, actions=KEYS))
    assert verdict.ship is False
    assert "widen exploration" in verdict.reason


def test_a_concentrated_estimate_is_never_shipped():
    _bandit, log = make_log(n=400, epsilon="0.02")
    verdict = should_deploy(ips(log, ALWAYS_A2, actions=KEYS))
    assert verdict.ship is False
    assert "too little effective data" in verdict.reason


def test_a_policy_no_better_than_the_deployed_one_is_not_shipped():
    bandit, log = make_log(n=2000, epsilon="0.50")
    verdict = should_deploy(ips(log, LoggingPolicyEcho(bandit).probability,
                                actions=KEYS))
    assert verdict.ship is False
    assert "good enough" in verdict.reason


def test_a_genuinely_better_policy_is_shipped_with_its_numbers():
    _bandit, log = make_log(n=2000, epsilon="0.50")
    verdict = should_deploy(ips(log, ALWAYS_A2, actions=KEYS))
    assert verdict.ship is True
    assert "estimated improvement" in verdict.reason
    s = verdict.summary()
    assert s["ship"] is True and s["usable"] is True and s["method"] == "ips"


def test_the_improvement_bar_is_configurable_and_typed():
    _bandit, log = make_log(n=2000, epsilon="0.50")
    estimate = ips(log, ALWAYS_A2, actions=KEYS)
    assert should_deploy(estimate, min_improvement=D("0.90")).ship is False
    with pytest.raises(OfflineEvalError):
        should_deploy(estimate, min_improvement=0.01)


def test_a_greedy_policy_can_be_evaluated_before_being_deployed():
    """The end-to-end use: learn from a log, then ask whether acting greedily on
    what you learned would have been better than what you did."""
    bandit, log = make_log(n=2000, epsilon="0.50")
    learned = bandit.observe_all([(r.context_key,
                                  next(a for a in bandit.actions if a.key == r.action_key),
                                  r.reward == D("1")) for r in log])
    assert learned.greedy("ctx") == A2          # it found the better arm
    verdict = should_deploy(doubly_robust(log, GreedyPolicy(learned).probability,
                                          actions=KEYS, reward_model=perfect_model))
    assert verdict.ship is True


def test_estimate_summary_is_serialisable():
    _bandit, log = make_log(n=200, epsilon="0.30")
    s = ips(log, ALWAYS_A2, actions=KEYS).summary()
    for key in ("method", "value", "n", "logged_mean", "ess", "max_weight_share",
                "clipped", "identified", "concentrated", "usable", "unsupported",
                "improvement", "note"):
        assert key in s
    assert s["method"] == "ips" and s["unsupported"] == []
